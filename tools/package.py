"""Deterministic store/personal builds. No network, compiler or model download.

Store bundles the MIT-licensed IFRNet-S engine and its checkpoint natively
(models/ifrnet.bin, hash-verified). Everything Framegen - runtime, installer,
noncommercial weights hooks - remains personal-only and is excluded from the
store artifact, not runtime-hidden.
"""
from pathlib import Path
import argparse, copy, hashlib, json, re, zipfile
ROOT = Path(__file__).resolve().parents[1]
COMMON = ['build-flavor.js','content.js','fi-analytic.js','fi-quality.js','fi-core.js',
          'fi-webgpu.js','popup.html','popup.js','THIRD_PARTY_NOTICES.txt','LICENSE-ANALYTIC.txt']
# IFRNet-S runtime + attribution ship in both editions; the checkpoint is bundled.
IFRNET = ['neural/model-spec.js','neural/graph.js','neural/runtime.js','neural/client.js',
          'neural/LICENSE-IFRNet.txt','neural/LICENSE-ncnn-port.txt','neural/MODEL-CARD.md',
          'models/ifrnet.bin']
OPTIONAL = ['fi-neural-runtime.js','neural-model.js','fi-neural.js','models.html','models.js','models.css']
BINARY_ALLOW = {'third_party/ravu-lite/ravu-lite-lut3.bin','models/ifrnet.bin'}
STAMP = (2026,9,19,0,0,0)


def strip_personal(text: str) -> str:
    """Explicit, non-nested source regions; fail closed on malformed markers."""
    for start,end in [('/* PERSONAL_ONLY_BEGIN */','/* PERSONAL_ONLY_END */'),
                      ('<!-- PERSONAL_ONLY_BEGIN -->','<!-- PERSONAL_ONLY_END -->')]:
        pieces=[]
        while start in text:
            before,rest=text.split(start,1)
            if end not in rest or start in rest.split(end,1)[0]:
                raise ValueError('Unbalanced or nested personal-only regions')
            ignored,text=rest.split(end,1);pieces.append(before)
        if end in text: raise ValueError('Unbalanced personal-only end')
        text=''.join(pieces)+text
    return text


def entries_for(browser: str, flavor: str) -> dict[str, bytes]:
    personal=flavor=='personal'
    manifest=json.loads((ROOT/('manifest.json' if browser=='firefox' else 'manifest.chromium.json')).read_text())
    version=manifest['version']
    names=list(COMMON)+list(IFRNET)
    for folder in ['_locales','icons','third_party/ravu-lite']:
        names += [p.relative_to(ROOT).as_posix() for p in sorted((ROOT/folder).rglob('*')) if p.is_file()]
    if personal:
        names += OPTIONAL
        for folder in ['neural','third_party/framegen']:
            names += [p.relative_to(ROOT).as_posix() for p in sorted((ROOT/folder).rglob('*'))
                      if p.is_file() and p.suffix in ('.js','.md','.txt','')]
    else:
        for key in ['background','options_ui','optional_host_permissions','host_permissions']:
            manifest.pop(key,None)
        manifest['content_scripts'][0]['js']=[n for n in manifest['content_scripts'][0]['js'] if n in names]
    # Both editions bundle the MIT-licensed IFRNet-S checkpoint; Framegen weights
    # remain personal-only and are never swept from local user data.
    for group in manifest.get('web_accessible_resources',[]):
        group['resources']=[n for n in group['resources'] if n in names]
    names=list(dict.fromkeys(names))
    contents={n:(ROOT/n).read_bytes() for n in names}
    for name in ['content.js','popup.js','popup.html']:
        if not personal: contents[name]=strip_personal(contents[name].decode()).encode()
    if not personal:
        contents['THIRD_PARTY_NOTICES.txt']=contents['THIRD_PARTY_NOTICES.txt'].split(b'Optional Framegen backend (personal edition only)')[0].rstrip()+b'\n'
        s=contents['content.js'].decode()
        engine_old='((globalThis.VE_BUILD?.personal !== false ? ["analytic","classic","neural","ifrnet"] : ["analytic","classic"]).includes(value.fiEngine)) ? value.fiEngine : "analytic"'
        engine_new='(["analytic","classic","ifrnet"].includes(value.fiEngine)) ? value.fiEngine : "ifrnet"'
        assert engine_old in s, 'engine normalization pattern not found'
        s=s.replace(engine_old,engine_new)
        contents['content.js']=s.encode()
        # The store never downloads anything: strip the (personal-installer-only)
        # URL/origin from the model spec so no download endpoint ships at all.
        ms=contents['neural/model-spec.js'].decode()
        download_spec="    url: 'https://cdn.jsdelivr.net/gh/nihui/ifrnet-ncnn-vulkan@7e54b1caa8c9f94a052a7148a56a2f57b685609e/models/IFRNet_S_GoPro/ifrnet.bin',\n    origin: 'https://cdn.jsdelivr.net/*',\n"
        assert download_spec in ms, 'model-spec download url pattern not found'
        ms=ms.replace(download_spec,'')
        assert 'https://cdn.jsdelivr' not in ms and 'https://raw.githubusercontent' not in ms
        contents['neural/model-spec.js']=ms.encode()
    contents['build-flavor.js']=('/* Generated by tools/package.py; contains no secrets. */\n'+
        'globalThis.VE_BUILD = Object.freeze('+json.dumps({'flavor':flavor,'personal':personal,'version':version})+');\n').encode()
    # Distinct human-readable names, identical IDs for update compatibility. These
    # are alternative installations; do not enable both simultaneously on a page.
    for n in list(contents):
        if n.startswith('_locales/') and n.endswith('/messages.json'):
            data=json.loads(contents[n]);data['extensionName']['message']+=' · '+('Personal' if personal else 'Store')
            contents[n]=(json.dumps(data,ensure_ascii=False,indent=2)+'\n').encode()
    contents['manifest.json']=(json.dumps(manifest,indent=2)+'\n').encode()
    assert manifest['permissions']==['storage']
    assert all(n in contents for n in manifest['content_scripts'][0]['js'])
    assert len(contents['third_party/ravu-lite/ravu-lite-lut3.bin'])==59904
    assert len(contents['models/ifrnet.bin'])==5921992
    assert not any(n.endswith('.bin') and n not in BINARY_ALLOW for n in contents)
    if not personal:
        assert all(n in contents for n in IFRNET)
        assert not any(n in OPTIONAL or n=='neural/background.js' for n in contents)
        assert not any(n.startswith(('third_party/framegen/','models/rt_v7s')) for n in contents)
        assert b'VENeuralClient' in contents['content.js'] and b'function fiRequestIfrPair' in contents['content.js']
        assert not any(token in contents['content.js'] for token in [b'FiNeural.',b'function fiRequestNeuralPair'])
        assert not any(token in contents['popup.js'] for token in [b'cdn.jsdelivr',b'raw.githubusercontent',b've-model-download',b've-model-import'])
        assert b'id="modelSetup"' not in contents['popup.html'] and b'id="ifrSetup"' not in contents['popup.html']
    return contents


def write_zip(path: Path, entries: dict[str, bytes]):
    path.parent.mkdir(parents=True,exist_ok=True)
    with zipfile.ZipFile(path,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
        for name,data in sorted(entries.items()):
            i=zipfile.ZipInfo(name,date_time=STAMP);i.compress_type=zipfile.ZIP_DEFLATED;i.external_attr=0o644<<16;z.writestr(i,data)
    with zipfile.ZipFile(path) as z: assert z.testzip() is None


def build(output: Path,flavor='all'):
    version=json.loads((ROOT/'manifest.json').read_text())['version']
    if version != json.loads((ROOT/'manifest.chromium.json').read_text())['version'] or not re.fullmatch(r'\d+(?:\.\d+){0,3}',version):
        raise ValueError('Invalid or unequal manifest versions')
    results=[]
    for f in ['store','personal'] if flavor=='all' else [flavor]:
        for browser in ['firefox','chromium']:
            entries=entries_for(browser,f);name=f'video-enhancer-{version}-{f}-{browser}.zip';p=output/name
            write_zip(p,entries)
            row={'file':name,'flavor':f,'browser':browser,'bytes':p.stat().st_size,
                 'sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'neuralWeightsBundled':'models/ifrnet.bin' in entries,
                 'files':{n:hashlib.sha256(d).hexdigest() for n,d in sorted(entries.items())}}
            results.append(row);print(json.dumps({k:v for k,v in row.items() if k!='files'}))
    (output/'build-manifest.json').write_text(json.dumps(results,indent=2)+'\n')
    return results

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--output',type=Path,default=ROOT/'dist')
    ap.add_argument('--flavor',choices=['all','store','personal'],default='all');a=ap.parse_args();build(a.output,a.flavor)
